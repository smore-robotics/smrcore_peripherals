#!/usr/bin/env python3
"""Prepare an immutable release diff and validate/render Codex draft notes."""
import argparse
import html
import json
import os
from pathlib import Path
import re
import subprocess

from version_history import GROUPS, git, section


def select_base(releases, target, root):
    candidates = []
    for release in releases:
        tag = release['tag_name']
        if release.get('draft') or release.get('prerelease') or not re.fullmatch(r'v(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)', tag):
            continue
        sha = git('rev-parse', '--verify', tag + '^{commit}', root=root)
        result = subprocess.run(['git', 'merge-base', '--is-ancestor', sha, target], cwd=root)
        if result.returncode == 1:
            continue
        if result.returncode:
            raise RuntimeError('Failed to resolve release ancestry')
        candidates.append((int(git('rev-list', '--count', f'{sha}..{target}', root=root)), tag, sha))
    if not candidates:
        raise ValueError('No published ancestor release; establish a baseline release first')
    _, tag, sha = min(candidates)
    return tag, sha


def prepare(root, output, releases, repository):
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
        raise ValueError('Invalid repository')
    if git('rev-parse', '--is-shallow-repository', root=root) != 'false':
        raise ValueError('Full Git history is required')
    target = git('rev-parse', 'HEAD', root=root)
    tag, base = select_base(releases, target, root)
    commits = git('rev-list', '--reverse', f'{base}..{target}', root=root).splitlines()
    metadata = {'repository': repository, 'base_tag': tag, 'base_sha': base,
                'target_sha': target, 'commits': commits,
                'sdk_version': (root / '.sdk-version').read_text().strip()}
    output.mkdir(parents=True, exist_ok=True)
    (output / 'context.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+'\n')
    # Content is evidence only, never interpolated into the controlling prompt.
    (output / 'changes.diff').write_text(git('diff', '--no-ext-diff', '--no-textconv', '--find-renames', base, target, '--', '.', root=root)+'\n')
    (output / 'commits.txt').write_text(git('log', '--format=fuller', f'{base}..{target}', root=root)+'\n')
    for language in ('zh', 'en'):
        text = section('Unreleased', target, (tag, base), language, repository, root)
        (output / f'fallback-{language}.md').write_text(text)
    return metadata


def validate(data, context):
    if set(data) != {'groups', 'uncertainties'}:
        raise ValueError('Unexpected output fields')
    if not isinstance(data['groups'], list) or not 1 <= len(data['groups']) <= len(GROUPS):
        raise ValueError('Missing or excessive groups')
    seen = set()
    count = 0
    for group in data['groups']:
        if set(group) != {'category', 'entries'} or group['category'] not in GROUPS or group['category'] in seen:
            raise ValueError('Invalid or repeated category')
        seen.add(group['category'])
        if not isinstance(group['entries'], list) or not group['entries']:
            raise ValueError('Empty group')
        for entry in group['entries']:
            if set(entry) != {'zh', 'en', 'commits'}:
                raise ValueError('Invalid entry')
            for lang in ('zh', 'en'):
                if not isinstance(entry[lang], str) or not 1 <= len(entry[lang].strip()) <= 2000:
                    raise ValueError('Invalid bilingual text')
            if not isinstance(entry['commits'], list) or not entry['commits'] or any(c not in context['commits'] for c in entry['commits']):
                raise ValueError('Evidence commit outside change range')
            count += 1
    if count > 40:
        raise ValueError('Too many entries')
    if not isinstance(data['uncertainties'], list) or len(data['uncertainties']) > 20:
        raise ValueError('Invalid uncertainties')
    for item in data['uncertainties']:
        if set(item) != {'zh', 'en'} or any(not isinstance(item[k], str) or not 1 <= len(item[k]) <= 2000 for k in ('zh', 'en')):
            raise ValueError('Invalid uncertainty')


def prose(text):
    return html.escape(text.strip(), quote=False).replace('\n', ' ').replace('[', '\\[').replace(']', '\\]')


def render(data, context, lang):
    zh = lang == 'zh'
    lines = ['# '+('版本说明草稿' if zh else 'Release notes draft'), '',
             ('Codex 根据代码差异生成，尚未人工审核。' if zh else 'Generated by Codex from code changes; not yet reviewed.'), '',
             f"{context['base_tag']} → `{context['target_sha']}` · SDK `{context['sdk_version']}`", '']
    for group in data['groups']:
        lines += ['## '+GROUPS[group['category']][0 if zh else 1], '']
        for entry in group['entries']:
            refs = ', '.join(f"[{c[:7]}](https://github.com/{context['repository']}/commit/{c})" for c in entry['commits'])
            lines.append(f'- {prose(entry[lang])} ({refs})')
        lines.append('')
    if data['uncertainties']:
        lines += ['## '+('待核实' if zh else 'Needs verification'), '']
        lines += ['- '+prose(item[lang]) for item in data['uncertainties']]
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest='command', required=True)
    prep = sub.add_parser('prepare')
    prep.add_argument('--releases', type=Path, required=True)
    prep.add_argument('--repository', required=True)
    prep.add_argument('--output', type=Path, required=True)
    finish = sub.add_parser('render')
    finish.add_argument('--input', type=Path, required=True)
    finish.add_argument('--output', type=Path, required=True)
    finish.add_argument('--status', choices=['generated', 'missing-key', 'no-changes', 'failed'], required=True)
    args = parser.parse_args()
    if args.command == 'prepare':
        context = prepare(Path.cwd(), args.output, json.loads(args.releases.read_text()), args.repository)
        if os.environ.get('GITHUB_OUTPUT'):
            with open(os.environ['GITHUB_OUTPUT'], 'a') as f:
                print('has_changes='+str(bool(context['commits'])).lower(), file=f)
        return
    context = json.loads((args.input / 'context.json').read_text())
    args.output.mkdir(parents=True, exist_ok=True)
    status = args.status
    data = None
    if status == 'generated':
        try:
            raw = os.environ.get('CODEX_FINAL_MESSAGE', '')
            if len(raw.encode()) > 100000:
                raise ValueError('Draft too large')
            data = json.loads(raw)
            validate(data, context)
        except (ValueError, TypeError, KeyError):
            status = 'invalid-output'
    for lang in ('zh', 'en'):
        text = render(data, context, lang) if status == 'generated' else (
            f'# Codex draft status: {status}\n\n'+(args.input / f'fallback-{lang}.md').read_text())
        (args.output / f'release-notes-{lang}.md').write_text(text)
    (args.output / 'context.json').write_text(json.dumps({**context, 'status': status}, indent=2)+'\n')
    if status == 'generated':
        (args.output / 'draft.json').write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n')
    print('Draft status: '+status)
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a') as f:
            f.write(f'## Codex release notes: {status}\n\nDownload `codex-release-notes-{context["target_sha"]}` from this run.\n')
    if status in ('failed', 'invalid-output'):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
